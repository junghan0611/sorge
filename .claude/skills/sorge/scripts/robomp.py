def pass_show(path):
    r = sh(["pass", "show", path])
    if r.returncode != 0:
        raise RuntimeError(f"pass show {path} failed: {(r.stderr or '').strip() or ('exit ' + str(r.returncode))}")
    val = r.stdout.strip()
    if not val:
        raise RuntimeError(f"pass show {path} returned an empty value")
    return val


def gh_api(token, method, path, body=None):
    """GitHub REST 한 번. 토큰은 헤더로만 간다 — argv 에 실으면 같은 사용자의
    다른 프로세스가 `ps` 로 줍는다."""
    data = json.dumps(body).encode("utf-8") if body is not None else None
    req = urllib.request.Request(
        f"https://api.github.com{path}",
        data=data,
        method=method,
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "sorge-robomp",
            "Content-Type": "application/json",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            return resp.status, json.loads(resp.read() or b"null")
    except urllib.error.HTTPError as exc:
        try:
            return exc.code, json.loads(exc.read() or b"null")
        except ValueError:
            return exc.code, None
    except urllib.error.URLError as exc:
        raise RuntimeError(f"GitHub unreachable: {exc.reason}") from exc


def bot_writable_repos(dry, token, repos):
    """대장 대상 중 **봇이 실제로 판정을 쓸 수 있는 집**만 남긴다.

    읽기는 신호가 아니다. 대상 리포가 전부 public 이라 토큰이 없어도 200 이
    나온다. 쓰기만 신호이고, 쓰기는 두 가지로 막힌다:

    1. **토큰 종류.** fine-grained PAT 는 발급 계정이 *소유한* 리포에만 권한을
       줄 수 있다. collaborator 로 push 권한이 있어도 GLG 소유 리포에는
       `403 Resource not accessible by personal access token` 이 난다
       (2026-09-15 실측). classic + `public_repo` 여야 한다.
    2. **초대.** 초대되지 않은 집은 `404 Not Found` 다 — 권한 문제가 아니라
       봇이 그 집에 아예 없는 것이다.

    둘을 갈라 보여주고, 쓸 수 있는 집만 allowlist 로 넘긴다. 초대 안 된 집을
    allowlist 에 남기면 그 집 이슈마다 턴이 열려 403/404 로 죽는다 — 대장은
    대상을 정하지만 **닿을 수 있는지는 대장이 모른다.**
    """
    status, who = gh_api(token, "GET", "/user")
    login = (who or {}).get("login") if status == 200 else None
    check(
        dry,
        login == BOT_LOGIN,
        f"token owner = {login}",
        f"token owner is {login or f'unknown({status})'} — must be {BOT_LOGIN}",
    )

    writable, missing = [], []
    for repo in repos:
        status, info = gh_api(token, "GET", f"/repos/{repo}")
        if status == 200 and (info or {}).get("permissions", {}).get("push"):
            writable.append(repo)
        elif status == 200:
            # public 이라 읽기는 되지만 collaborator 가 아니다.
            missing.append((repo, "not invited (read-only)"))
        elif status == 404:
            missing.append((repo, "repo missing or private and not invited (404)"))
        else:
            missing.append((repo, f"unreachable ({status})"))

    if writable:
        # 한 집에서 무변경 PATCH 로 라벨 쓰기를 실제로 확인한다. push=true 가
        # 곧 이슈 쓰기라는 추론에 기대지 않는다 — 토큰 스코프가 좁으면
        # push 권한이 있어도 거부될 수 있다.
        #
        # 그러나 **dry-run 은 밖에 쓰지 않는다.** 무변경이라도 PATCH 는 쓰기이고,
        # GitHub 은 그것을 감사로그에 남긴다. dry-run 의 계약은 「아무것도 안
        # 바뀐다」이지 「같은 값으로 바뀐다」가 아니다 (terra 검수, 2026-09-15).
        probe = writable[0]
        status, labels = gh_api(token, "GET", f"/repos/{probe}/labels?per_page=1")
        if status != 200 or not isinstance(labels, list) or not labels:
            check(dry, False, "", f"{probe} can't read label list ({status})")
        elif dry:
            print(f"   [dry-run] would verify label write on {probe} with a no-op PATCH (not sent — dry-run writes nothing)")
        else:
            current = labels[0]
            body = {k: current[k] for k in ("name", "color", "description") if k in current}
            status, err = gh_api(token, "PATCH", f"/repos/{probe}/labels/{current['name']}", body)
            check(
                dry,
                status == 200,
                f"{probe} label write ok (no-op PATCH 200)",
                f"{probe} label write rejected ({status} {(err or {}).get('message', '')}) — "
                f"check that {BOT_LOGIN}'s token is classic + `public_repo`",
            )

    for repo, why in missing:
        print(f"   · excluded {repo} — {why}")
    check(
        dry,
        bool(writable),
        f"repos the bot can write {len(writable)}/{len(repos)} → {','.join(writable)}",
        f"{BOT_LOGIN} can't write to any of the {len(repos)} ledger-targeted repos — invite it as a collaborator first",
    )
    return writable


FORWARDER_HOOK_HOST = "webhook-forwarder.github.com"


def forwarder_hooks(token, repo):
    """그 리포에 남아 있는 `gh webhook forward` relay 훅의 id 들.

    forward 는 리포에 훅을 만들고 프로세스가 죽어도 남긴다. 남은 훅은 다음
    `on` 을 `422 Hook already exists` 로 즉사시키고, 배달은 아무도 안 받는
    relay 로 흘러간다. URL 호스트로만 골라낸다 — 사람이 만든 훅은 절대
    건드리지 않는다.
    """
    status, hooks = gh_api(token, "GET", f"/repos/{repo}/hooks")
    if status != 200 or not isinstance(hooks, list):
        return []
    return [h["id"] for h in hooks if FORWARDER_HOOK_HOST in str((h.get("config") or {}).get("url", ""))]



def check(dry, cond, ok_msg, fail_msg):
    """전제 하나를 찍는다. `--go` 에서 실패하면 그 자리에서 멈춘다."""
    if cond:
        print(f"   ✓ {ok_msg}")
        return True
    print(f"   ✗ {fail_msg}")
    if not dry:
        raise Halt(fail_msg)
    return False


def attempt(dry, label, fn):
    """fn() 을 실행하고 영수증을 찍는다. `--go` 에서 실패하면 멈춘다."""
    try:
        result = fn()
        print(f"   ✓ {label}")
        return result
    except Exception as exc:  # noqa: BLE001 — 원인 그대로 사유에 싣는다
        print(f"   ✗ {label} failed: {exc}")
        if not dry:
            raise Halt(f"{label} failed: {exc}") from exc
        return None


def launch(cmd, *, cwd, env, log_path, pidname):
    log_path.parent.mkdir(parents=True, exist_ok=True)
    pidfile_path(pidname).parent.mkdir(parents=True, exist_ok=True)
    logf = open(log_path, "ab")
    proc = subprocess.Popen(
        cmd,
        cwd=str(cwd),
        env=env,
        stdout=logf,
        stderr=subprocess.STDOUT,
        stdin=subprocess.DEVNULL,
        start_new_session=True,  # setsid 동격 — 이 세션이 끝나도 산다
    )
    pidfile_path(pidname).write_text(str(proc.pid))
    return proc.pid


def wait_port(host, port, timeout, label):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if port_alive(host, port):
            print(f"   ✓ {label} ready — {host}:{port}")
            return
        time.sleep(0.5)
    raise Halt(f"{label} didn't open {host}:{port} within {timeout}s — check the log")


def wait_http_ok(url, timeout, label):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=2) as resp:  # noqa: S310
                if resp.status < 500:
                    print(f"   ✓ {label} ready — {url} → {resp.status}")
                    return
        except (urllib.error.URLError, OSError):
            pass
        time.sleep(0.5)
    raise Halt(f"{label} didn't respond at {url} within {timeout}s — check the log")


def wait_log(log_path, pattern, timeout, label):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if log_path.exists():
            text = log_path.read_text(encoding="utf-8", errors="replace")
            if pattern.search(text):
                print(f"   ✓ {label} ready — log: {log_path}")
                return
        time.sleep(0.5)
    raise Halt(f"{label} didn't signal ready within {timeout}s — check the log: {log_path}")


