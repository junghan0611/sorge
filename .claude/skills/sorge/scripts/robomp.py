def _on_steps(dry, only=""):
    root = omp_root()
    robomp_src = root / "python" / "robomp"
    omprpc_src = root / "python" / "omp-rpc"

    print("1) fork check")
    check(
        dry,
        robomp_src.is_dir() and omprpc_src.is_dir(),
        f"{root}  (both python/robomp and python/omp-rpc exist)",
        f"{root} is missing python/robomp or python/omp-rpc — override with SORGE_OMP_ROOT",
    )

    print("\n2) gh extension check")
    ext = sh(["gh", "extension", "list"])
    has_webhook_ext = ext.returncode == 0 and "gh webhook" in ext.stdout
    check(
        dry,
        has_webhook_ext,
        "gh webhook extension installed",
        "gh webhook extension missing — `gh extension install cli/gh-webhook`",
    )

    print("\n3) venv setup")
    pyexe = str(VENV_DIR / "bin" / "python")
    pip = str(VENV_DIR / "bin" / "pip")
    if VENV_DIR.exists():
        print(f"   ✓ already exists: {VENV_DIR}")
    else:
        print(f"   {'would create' if dry else 'creating'}: python3 -m venv {VENV_DIR}")
        print(f"   {'would install' if dry else 'installing'}: pip install -e {omprpc_src}  (pip only — AGENTS.md)")
        print(f"   {'would install' if dry else 'installing'}: pip install -e {robomp_src}")
        if not dry:
            r = sh(["python3", "-m", "venv", str(VENV_DIR)])
            if r.returncode != 0:
                raise Halt(f"venv creation failed: {r.stderr.strip()}")
            for target in (omprpc_src, robomp_src):
                r = sh([pip, "install", "-e", str(target)])
                if r.returncode != 0:
                    raise Halt(f"pip install -e {target} failed: {r.stderr.strip()[-800:]}")
            print(f"   ✓ venv ready: {VENV_DIR}")

    print("\n4) ledger → allowlist (reusing board.ledger_houses())")
    # board.py 가 대장을 못 읽으면 여기서 sys.exit 로 바로 멈춘다 — 빈 대장을
    # "빚 0" 처럼 조용히 삼키지 않는 것이 board.py 의 규율이고, 여기서도 그대로다.
    ledger_repos = allowlist_repos()
    check(dry, len(ledger_repos) > 0, f"{len(ledger_repos)} assigned → {','.join(ledger_repos)}", "no repos assigned in the ledger — check LEDGER.md")
    # 대장은 대상을 정하고, 봇 토큰은 그중 닿을 수 있는 곳을 정한다. allowlist
    # 는 둘의 교집합이어야 한다 — 초대 안 된 집을 남기면 그 집 이슈마다 턴이
    # 열려 404 로 죽는다.
    bot_token = attempt(dry, f"pass {PASS_PAT_BOT} read", lambda: pass_show(PASS_PAT_BOT))
    allow_repos = bot_writable_repos(dry, bot_token, ledger_repos) if bot_token else ledger_repos

    # 좁은 시작. 대장은 그대로 두고 **이번 기동만** 몇 집으로 줄인다 — 새 모델과
    # 호흡을 맞추는 첫 시간에 열다섯 집이 동시에 노출되지 않게 (GLG, 2026-09-15:
    # "간단한 시작을 맡겨봐야하는데 … 일반적인 스위퍼하는 역할부터").
    # 대장을 고치는 것이 아니므로 다음 `on` 은 다시 전부가 기본이다.
    if only:
        wanted = {o.strip() for o in only.split(",") if o.strip()}
        picked = [r for r in allow_repos if r in wanted or r.split("/")[-1] in wanted]
        unknown = sorted(wanted - set(picked) - {r.split("/")[-1] for r in picked})
        if unknown:
            raise Halt(
                f"--only names repos that are not reachable targets: {', '.join(unknown)}\n"
                f"     reachable right now: {', '.join(allow_repos)}"
            )
        print(f"   --only → narrowed this start to {len(picked)}/{len(allow_repos)}: {','.join(picked)}")
        print("     (the ledger is untouched — the next `on` without --only is all of them again)")
        allow_repos = picked

    print("\n5) resolve paths (absolute — relative paths break because the worktree pool resolves them against cwd)")
    workspace_root = DATA_DIR / "workspaces"
    sqlite_path = DATA_DIR / "robomp.sqlite"
    app_log_dir = DATA_DIR / "logs"
    natives_root = DATA_DIR / "cache" / "pi-natives"
    for p in (workspace_root, sqlite_path.parent, app_log_dir, natives_root):
        print(f"   {'would create' if dry else 'creating'}: {p}")
        if not dry:
            p.mkdir(parents=True, exist_ok=True)

    print("\n6) config file: " + str(ROBOMP_ENV))
    existing = parse_env_file(ROBOMP_ENV)
    webhook_secret = existing.get("GITHUB_WEBHOOK_SECRET") or secrets.token_hex(32)
    hmac_key = existing.get("ROBOMP_GH_PROXY_HMAC_KEY") or secrets.token_hex(32)
    print(f"   GITHUB_WEBHOOK_SECRET     {'reused' if 'GITHUB_WEBHOOK_SECRET' in existing else 'newly generated'} (value not printed)")
    print(f"   ROBOMP_GH_PROXY_HMAC_KEY  {'reused' if 'ROBOMP_GH_PROXY_HMAC_KEY' in existing else 'newly generated'} (value not printed)")
    provider_key = os.environ.get(PROVIDER_KEY_ENV, "") or existing.get(PROVIDER_KEY_ENV, "")
    if not provider_key and not dry:
        raise Halt(
            f"{PROVIDER_KEY_ENV} is missing — can't run with {MODEL}.\n"
            f"     the child omp starts in an isolated XDG and can't see the host subscription (agent.db). "
            f"put the key in your shell and re-run `on`: export {PROVIDER_KEY_ENV}=..."
        )
    print(f"   {PROVIDER_KEY_ENV}            {'read from environment' if os.environ.get(PROVIDER_KEY_ENV) else ('reused from existing file' if provider_key else 'missing')} (value not printed)")
    values = {
        "GITHUB_WEBHOOK_SECRET": webhook_secret,
        "ROBOMP_BOT_LOGIN": BOT_LOGIN,
        # config.py 의 orchestrator Settings 는 이 둘을 필수로 요구한다
        # (`git_author_email: str = Field(..., ...)`, 기본값 없음). stock full
        # 프로파일은 gh_push_branch 를 실제로 쓰므로 여기 값이 커밋 저자가 된다.
        "ROBOMP_GIT_AUTHOR_NAME": existing.get("ROBOMP_GIT_AUTHOR_NAME", "sorge-robomp"),
        "ROBOMP_GIT_AUTHOR_EMAIL": existing.get("ROBOMP_GIT_AUTHOR_EMAIL", "sorge-robomp@users.noreply.github.com"),
        "ROBOMP_MODEL": MODEL,
        "ROBOMP_THINKING": THINKING,
        # 자식 omp 는 격리 XDG 로 뜨고 호스트 `agent.db` 를 못 본다 (stock 은
        # agent_dir 설정 자체가 없다). 그래서 자격증명은 provider API 키 축뿐이고,
        # 이 키는 stock 의 scrub 목록(`worker.py:127-134`)에 없어서 자식까지 닿는다.
        PROVIDER_KEY_ENV: provider_key,
        "ROBOMP_REPO_ALLOWLIST": ",".join(allow_repos),
        "ROBOMP_GH_PROXY_URL": f"http://{PROXY_HOST}:{PROXY_PORT}",
        "ROBOMP_GH_PROXY_HMAC_KEY": hmac_key,
        "ROBOMP_WORKSPACE_ROOT": str(workspace_root),
        "ROBOMP_SQLITE_PATH": str(sqlite_path),
        "ROBOMP_LOG_DIR": str(app_log_dir),
        "ROBOMP_NATIVES_CACHE_ROOT": str(natives_root),
        # 나머지 동작은 stock 기본값을 그대로 둔다 — 우리가 값을 적는 순간
        # 그것이 관리 대상이 되고, omp 버전업 때 기본값 변화를 못 따라간다.
        # 예외 하나: 자동 close 는 GLG 의 이슈를 무인으로 닫으므로 끈다.
        "ROBOMP_QUESTION_AUTOCLOSE_ENABLED": "false",
        "ROBOMP_BIND_HOST": ORCH_HOST,
        "ROBOMP_BIND_PORT": str(ORCH_PORT),
    }
    for k, v in values.items():
        if k in SECRET_KEYS:
            continue
        print(f"   {k}={v}")
    if dry:
        print(f"   [dry-run] not writing {ROBOMP_ENV} (would become 0600)")
    else:
        write_env_file(ROBOMP_ENV, values)
        print(f"   ✓ wrote: {ROBOMP_ENV} (0600)")

    print("\n7) config file: " + str(PROXY_ENV))
    if dry:
        print(f"   [dry-run] not writing {PROXY_ENV} (0600, would hold only GITHUB_TOKEN — already read and checked in step 4)")
    else:
        write_env_file(PROXY_ENV, {"GITHUB_TOKEN": bot_token})
        print(f"   ✓ wrote: {PROXY_ENV} (0600, GITHUB_TOKEN only)")

    print("\n8) port check")
    check(dry, not port_alive(PROXY_HOST, PROXY_PORT), f"{PROXY_HOST}:{PROXY_PORT} free", f"{PROXY_HOST}:{PROXY_PORT} already in use — run `off` first or check that process")
    check(dry, not port_alive(ORCH_HOST, ORCH_PORT), f"{ORCH_HOST}:{ORCH_PORT} free", f"{ORCH_HOST}:{ORCH_PORT} already in use — run `off` first or check that process")

    print("\n9) gh-proxy startup")
    proxy_cmd = [pyexe, "-m", "robomp.proxy", "serve"]
    proxy_log = LOG_DIR / "gh-proxy.log"
    print(f"   {'would launch' if dry else 'launching'}: {' '.join(shlex.quote(c) for c in proxy_cmd)}")
    print(f"     cwd={robomp_src}")
    print(f"     env: GITHUB_TOKEN(proxy only) · ROBOMP_GH_PROXY_HMAC_KEY · ROBOMP_WORKSPACE_ROOT · ROBOMP_LOG_DIR")
    print(f"     bind: ROBOMP_GH_PROXY_BIND_HOST={PROXY_HOST} ROBOMP_GH_PROXY_BIND_PORT={PROXY_PORT}")
    print(f"     log: {proxy_log}  pidfile: {pidfile_path('gh-proxy')}")
    print(f"     readiness check: successful connection to {PROXY_HOST}:{PROXY_PORT} (up to 30s)")
    if not dry:
        proxy_env = dict(os.environ)
        proxy_env.update(parse_env_file(ROBOMP_ENV))  # HMAC key, workspace/log 경로 공유
        proxy_env.update(parse_env_file(PROXY_ENV))  # GITHUB_TOKEN
        proxy_env["ROBOMP_GH_PROXY_BIND_HOST"] = PROXY_HOST
        proxy_env["ROBOMP_GH_PROXY_BIND_PORT"] = str(PROXY_PORT)
        launch(proxy_cmd, cwd=robomp_src, env=proxy_env, log_path=proxy_log, pidname="gh-proxy")
        wait_port(PROXY_HOST, PROXY_PORT, 30, "gh-proxy")

    print("\n10) orchestrator startup")
    orch_cmd = [pyexe, "-m", "robomp", "serve"]
    orch_log = LOG_DIR / "orchestrator.log"
    print(f"   {'would launch' if dry else 'launching'}: {' '.join(shlex.quote(c) for c in orch_cmd)}")
    print(f"     cwd={robomp_src}  env: all of {ROBOMP_ENV} (GITHUB_TOKEN withheld — serve rejects it)")
    print(f"     bind: ROBOMP_BIND_HOST={ORCH_HOST} ROBOMP_BIND_PORT={ORCH_PORT}")
    print(f"     log: {orch_log}  pidfile: {pidfile_path('orchestrator')}")
    print(f"     readiness check: GET http://{ORCH_HOST}:{ORCH_PORT}/healthz (up to 30s)")
    if not dry:
        orch_env = dict(os.environ)
        orch_env.update(parse_env_file(ROBOMP_ENV))
        orch_env.pop("GITHUB_TOKEN", None)  # serve() 가 이걸 보면 SystemExit — 절대 안 준다
        launch(orch_cmd, cwd=robomp_src, env=orch_env, log_path=orch_log, pidname="orchestrator")
        wait_http_ok(f"http://{ORCH_HOST}:{ORCH_PORT}/healthz", 30, "orchestrator")

    print(f"\n11) gh webhook forward ({len(allow_repos)} repos, --events=issues)")
    classic_pat = attempt(dry, f"pass {PASS_PAT_CLASSIC} read (admin:repo_hook, forward only)", lambda: pass_show(PASS_PAT_CLASSIC))
    for repo in allow_repos:
        stale = forwarder_hooks(classic_pat, repo) if classic_pat else []
        for hook_id in stale:
            # `gh webhook forward` 는 repo 에 relay 훅을 만들고, 프로세스가
            # 죽어도 그 훅을 남긴다. 다음 `on` 은 그걸 보고
            # `422 Hook already exists` 로 즉사한다 — 켜기 전에 우리가 만든
            # 훅만 지운다(다른 훅은 건드리지 않는다).
            print(f"   {'would delete' if dry else 'deleting'}: {repo}'s leftover forwarder hook {hook_id}")
            if not dry:
                status, _ = gh_api(classic_pat, "DELETE", f"/repos/{repo}/hooks/{hook_id}")
                if status not in (204, 404):
                    raise Halt(f"{repo} forwarder hook {hook_id} deletion failed ({status})")
    for repo in allow_repos:
        name = forward_name(repo)
        fwd_log = LOG_DIR / f"{name}.log"
        printable = [
            "gh", "webhook", "forward",
            f"--repo={repo}", "--events=issues",
            f"--url=http://{ORCH_HOST}:{ORCH_PORT}/webhook/github",
            "--secret=***",
        ]
        print(f"   {'would launch' if dry else 'launching'}: {' '.join(printable)}")
        print(f"     env: GH_TOKEN=<forge classic PAT>  log: {fwd_log}  pidfile: {pidfile_path(name)}")
        print(f"     readiness check: forward/listen signal in the log (up to 20s)")
        if not dry:
            real_cmd = [
                "gh", "webhook", "forward",
                f"--repo={repo}", "--events=issues",
                f"--url=http://{ORCH_HOST}:{ORCH_PORT}/webhook/github",
                f"--secret={webhook_secret}",
            ]
            fwd_env = dict(os.environ)
            fwd_env["GH_TOKEN"] = classic_pat
            launch(real_cmd, cwd=robomp_src, env=fwd_env, log_path=fwd_log, pidname=name)
            wait_log(fwd_log, re.compile(r"[Ff]orward|[Ll]isten|[Cc]onnect"), 20, name)

    print()
    if dry:
        print("dry-run done — to actually turn it on: `./run.sh robomp on --go`")
    else:
        print("✓ started. Check with `./run.sh robomp status`.")


def cmd_on(args):
    dry = not args.go
    print(f"━━ sorge robomp · on · {'dry-run (add --go to actually run)' if dry else 'run'} ━━\n")
    try:
        _on_steps(dry, getattr(args, "only", "") or "")
    except Halt as exc:
        print(f"\nhalted: {exc}")
        sys.exit(1)


# ── off ──────────────────────────────────────────────────────────────────


def cmd_off(_args):
    print("━━ sorge robomp · off ━━\n")
    cfg = parse_env_file(ROBOMP_ENV)
    repos = [r for r in cfg.get("ROBOMP_REPO_ALLOWLIST", "").split(",") if r]
    names = ["orchestrator", "gh-proxy"] + [forward_name(r) for r in repos]
    # 대장이 줄어든 뒤에도 남았을 pidfile 을 놓치지 않는다.
    if STATE_DIR.exists():
        for p in STATE_DIR.glob("webhook-forward-*.pid"):
            if p.stem not in names:
                names.append(p.stem)

    any_running = False
    for name in names:
        alive, pid = proc_alive(name)
        if not alive:
            continue
        any_running = True
        print(f"  {name}: SIGTERM → pid {pid}")
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        for _ in range(20):
            if not pid_alive(pid):
                break
            time.sleep(0.5)
        if pid_alive(pid):
            print("    not dying → SIGKILL")
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        print("    ✓ stopped")
        pidfile_path(name).unlink(missing_ok=True)

    # 프로세스를 내려도 GitHub 쪽 relay 훅은 남는다. 남기면 배달이 아무도
    # 안 받는 곳으로 흐르고, 다음 `on` 은 `422 Hook already exists` 로 죽는다.
    if repos:
        try:
            classic_pat = pass_show(PASS_PAT_CLASSIC)
        except RuntimeError as exc:
            print(f"  · could not clean up relay hooks — {exc}")
        else:
            for repo in repos:
                for hook_id in forwarder_hooks(classic_pat, repo):
                    status, _ = gh_api(classic_pat, "DELETE", f"/repos/{repo}/hooks/{hook_id}")
                    mark = "✓" if status in (204, 404) else f"✗({status})"
                    print(f"  {mark} {repo} relay hook {hook_id} deleted")

    if not any_running:
        print("  process was already stopped.")


# ── judge ────────────────────────────────────────────────────────────────


def cmd_judge(args):
    """이슈 하나를 손으로 판정 큐에 넣는다 — 웹훅이 온 것처럼.

    사건을 기다리지 않고 지금 판정을 보고 싶을 때, 그리고 훅이 끊겼던 동안
    지나간 이슈를 따라잡을 때 쓴다. 판정 자체는 도는 orchestrator 가 한다 —
    이 명령은 줄에 세우고 빠진다.
    """
    print(f"━━ sorge robomp · judge {args.ref} ━━\n")
    alive, _ = proc_alive("orchestrator")
    if not alive:
        print("  ✗ orchestrator is not up — run `./run.sh robomp on --go` first")
        sys.exit(1)
    cfg = parse_env_file(ROBOMP_ENV)
    if not cfg:
        print(f"  ✗ {ROBOMP_ENV} is missing — run `./run.sh robomp on --go` first")
        sys.exit(1)
    env = dict(os.environ)
    env.update(cfg)
    env.pop("GITHUB_TOKEN", None)  # orchestrator 쪽 설정이다 — PAT 는 gh-proxy 만 든다
    pyexe = str(VENV_DIR / "bin" / "python")
    r = subprocess.run([pyexe, "-m", "robomp", "triage", args.ref], cwd=str(omp_root() / "python" / "robomp"), env=env)
    if r.returncode != 0:
        sys.exit(r.returncode)
    print("\n  ✓ queued. Follow along in the log:")
    print(f"    tail -f {LOG_DIR / 'orchestrator.log'}")


# ── main ─────────────────────────────────────────────────────────────────


def main():
    ap = argparse.ArgumentParser(description="sorge robomp — issue hook loop ON switch")
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("status", help="gh-proxy/orchestrator/webhook forward liveness + allowlist + recent events")
    sub.add_parser("allowlist", help="LEDGER.md-assigned repos → owner/repo list (reuses board.ledger_houses)")
    p_on = sub.add_parser("on", help="turns on in order: venv → env file → gh-proxy → orchestrator → webhook forward")
    p_on.add_argument("--go", action="store_true", help="actually turn it on (default is dry-run — prints the plan only, no side effects)")
    p_on.add_argument(
        "--only",
        default="",
        metavar="REPO[,REPO]",
        help="narrow THIS start to a few repos (ledger stays untouched; short names ok, e.g. --only sorge)",
    )
    sub.add_parser("off", help="gracefully stops everything by pidfile (SIGTERM → check → SIGKILL)")
    p_judge = sub.add_parser("judge", help="manually queue one issue for judging (doesn't wait for a webhook)")
    p_judge.add_argument("ref", help="owner/repo#NN — must be a ledger target and inside the allowlist")
    a = ap.parse_args()

    if a.cmd == "status":
        cmd_status(a)
    elif a.cmd == "allowlist":
        cmd_allowlist(a)
    elif a.cmd == "on":
        cmd_on(a)
    elif a.cmd == "off":
        cmd_off(a)
    elif a.cmd == "judge":
        cmd_judge(a)
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
